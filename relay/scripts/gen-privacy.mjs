#!/usr/bin/env node
// Renders docs/privacy.md into relay/src/privacy.generated.ts, served at /privacy.
// Usage: node relay/scripts/gen-privacy.mjs [--check]   (--check: exit 1 if the file is stale)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Marked } from "marked";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const source = join(root, "docs", "privacy.md");
const target = join(root, "relay", "src", "privacy.generated.ts");

/** GitHub's heading anchors, so links like (#online-mode-tabcrew-relay) work in both places. */
function slug(text) {
  return text
    .toLowerCase()
    .replace(/<[^>]+>/g, "")
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .trim()
    .replace(/\s/g, "-");
}

export function render(markdown) {
  const body = markdown.replace(/^---\n[\s\S]*?\n---\n/, "");
  const marked = new Marked({
    gfm: true,
    renderer: {
      heading({ tokens, depth, text }) {
        return `<h${depth} id="${slug(text)}">${this.parser.parseInline(tokens)}</h${depth}>\n`;
      },
    },
  });
  return marked.parse(body);
}

const html = render(readFileSync(source, "utf8"));
const out = `// Generated by relay/scripts/gen-privacy.mjs from docs/privacy.md. Do not edit.\nexport const PRIVACY_HTML = ${JSON.stringify(html)};\n`;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== out) {
    console.error("relay/src/privacy.generated.ts is stale: run node relay/scripts/gen-privacy.mjs");
    process.exit(1);
  }
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
